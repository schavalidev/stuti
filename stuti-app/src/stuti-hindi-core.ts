  const norm = (s) => (s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");

  function attach() {
    const hs = (STUTI && STUTI.hymns) || [];
    if (!hs.length) return false;
    let hit = 0;
    function apply(map, key) {
      Object.keys(map).forEach(function (title) {
        const t = norm(title), rows = map[title];
        hs.filter(function (h) { return norm(h.title) === t && h.verses && h.verses.length; })
          .forEach(function (h) { hit++; h.verses.forEach(function (v, i) { if (rows[i]) v[key] = rows[i]; }); });
      });
    }
    apply(HI, "hi");
    apply(TE, "tel");
    return hit > 0;
  }
  if (!attach()) document.addEventListener("DOMContentLoaded", attach);
