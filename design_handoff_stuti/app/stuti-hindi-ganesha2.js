  const norm = (s) => (s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");

  /* attach once the library pool is built and stuti-texts.js has hung
     the verses on it — a text on two shelves gets both copies */
  function attach() {
    const hs = (window.STUTI && window.STUTI.hymns) || [];
    if (!hs.length) return false;
    let hit = 0;
    Object.keys(HI).forEach(function (title) {
      const t = norm(title), rec = HI[title];
      hs.filter(function (h) { return norm(h.title) === t && h.verses && h.verses.length; })
        .forEach(function (h) {
          hit++;
          h.verses.forEach(function (v, i) { if (rec.v[i]) v.hi = rec.v[i]; });
          if (rec.sections && h.sections) h.sections.forEach(function (s, i) { if (rec.sections[i]) s.hi = rec.sections[i]; });
        });
    });
    return hit > 0;
  }
  if (!attach()) document.addEventListener("DOMContentLoaded", attach);
